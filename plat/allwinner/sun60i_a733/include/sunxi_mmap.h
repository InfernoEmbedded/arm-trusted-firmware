#ifndef SUNXI_MMAP_H
#define SUNXI_MMAP_H

/* Memory regions */
#define SUNXI_ROM_BASE			0x00000000
#define SUNXI_ROM_SIZE			0x00010000
#define SUNXI_SRAM_BASE			0x00040000
#define SUNXI_SRAM_SIZE			0x00034000
#define SUNXI_DEV_BASE			0x00000000
#define SUNXI_DEV_SIZE			0x40000000
#define SUNXI_DRAM_BASE			0x40000000
#define SUNXI_DRAM_VIRT_BASE		0x4a000000
#define BL31_BASE			0x48000000
#define BL31_LIMIT			(BL31_BASE + 0x00200000)

/* Memory-mapped devices */
#define SUNXI_PIO_BASE			0x02000000
#define SUNXI_CCU_BASE			0x02002000
#define SUNXI_WDOG_BASE			0x02050000
#define SUNXI_SPC_BASE			0x02054000
#define SUNXI_UART0_BASE		0x02500000
#define SUNXI_SYSCON_BASE		0x03000000
#define SUNXI_MSGBOX_BASE		0x03004000
#define SUNXI_SID_BASE			0x03006000
#define SUNXI_GICD_BASE			0x03400000
#define SUNXI_GICR_BASE			0x03460000
#define SUNXI_DMA_BASE			0x04601000
#define SUNXI_DMA0_BASE			0x04024000
#define SUNXI_IOMMU0_BASE		0x03900000
#define SUNXI_IOMMU1_BASE		0x03910000
#define SUNXI_IOMMU_AUTO_BYPASS_REG	0x0030
#define SUNXI_IOMMU_AUTO_BYPASS_ALL	0xffffffff
#define SUNXI_R_SPC_BASE		0x07002000
#define SUNXI_R_TZMA_BASE		0x07003000
#define SUNXI_R_PRCM_BASE		0x07010000
#define SUNXI_R_WDOG_BASE		0x07021000
#define SUNXI_R_PIO_BASE		0x07025000
#define SUNXI_R_CPUCFG_BASE		0x07050000
#define SUNXI_R_UART_BASE		0x07080000
#define SUNXI_R_I2C_BASE		0x07083000
#define SUNXI_RTC_BASE			0x07090000
#define SUNXI_R_MSGBOX_BASE		0x07094000
#define SUNXI_CPUCFG_BASE		0x08000000
#define SUNXI_CLUSTER_CFG_BASE		0x08860000
#define SUNXI_CPU_PLL_CFG_BASE		0x08870000

#define SUNXI_SYSCON_REMAP_REG		(SUNXI_SYSCON_BASE + 0x9008)

#endif /* SUNXI_MMAP_H */
